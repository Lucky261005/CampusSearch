"""Renders evaluation/RESULTS.md from results.json. Every number comes from the run."""

from pathlib import Path

ANALYSIS = Path(__file__).parent / "analysis.md"
CHECK_NAMES = {
    "faithful_answer_accepted": "Faithful, correctly cited answer is accepted",
    "citations_resolve_to_stored_records": "Citations resolve to stored chunk, URL, title, excerpt, provenance",
    "illustrative_source_labelled": "Illustrative sources labelled as not official",
    "fabricated_citation_id_rejected": "Fabricated citation ID rejected",
    "unsupported_marker_rejected": "Unsupported [n] marker rejected",
    "unsupported_number_rejected": "Number absent from cited text rejected",
    "misquoted_evidence_rejected": "Quote not present in source rejected",
    "honest_model_insufficient": "Unanswerable question → insufficient evidence",
    "fabricated_figure_rejected": "Unanswerable question + model inventing a figure → rejected",
}


def f(v, digits=3):
    return "—" if v is None else f"{v:.{digits}f}"


def render(r: dict, data: dict, analysis: Path = ANALYSIS) -> str:
    c, env, lat = r["corpus"], r["environment"], r["latency"]
    version = r.get("benchmark", "v1")
    modes = list(r["retrieval"])
    L = [
        f"# CampusSearch evaluation results ({version})",
        "",
        f"_Generated by `python -m evaluation.run --benchmark {version}` at {r['generated_at']}. "
        f"Dataset version {data.get('version', 1)}, corpus fingerprint `{c['fingerprint']}`, embedding "
        f"model {'available' if r['semantic']['available'] else 'UNAVAILABLE'}. Do not edit by hand; "
        f"edit `evaluation/{analysis.relative_to(Path(__file__).parent).as_posix()}` for the discussion._",
        "",
        "> **Read this first.** The corpus has "
        f"{c['documents']} documents ({c['official_documents']} from official university URLs, "
        f"{c.get('supplied_documents', 0)} supplied locally without a verified official URL, "
        f"{c['illustrative_documents']} illustrative sample records) split into {c['chunks']} chunks. "
        "Illustrative records are synthetic, written for this project, and are not official CHRIST "
        "University information. The questions and relevance judgments were written by the project "
        "author after reading the corpus. These numbers describe this corpus and question set only; "
        "they are not evidence about real-world search quality.",
        "",
        "## Retrieval quality and latency",
        "",
        f"{r['retrieval'][modes[0]]['judged_queries']} judged queries "
        f"(queries with no relevant documents are excluded and reported below). "
        f"Latency: {lat['repeats']} timed passes over all {r['queries']['total']} queries after "
        f"{lat['warmup_passes']} warm-up pass.",
        "",
        "| Mode | Recall@5 | nDCG@10 | MRR | p50 latency | p95 latency |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for m in ("keyword", "semantic", "hybrid"):
        if m in r["retrieval"]:
            x, t = r["retrieval"][m], lat["modes"][m]
            L.append(f"| {m.title()} | {f(x['recall@5'])} | {f(x['ndcg@10'])} | {f(x['mrr'])} | "
                     f"{t['p50_ms']:.1f} ms | {t['p95_ms']:.1f} ms |")
        else:
            L.append(f"| {m.title()} | unavailable | unavailable | unavailable | unavailable | unavailable |")
    if not r["semantic"]["available"]:
        L += ["", f"Semantic and hybrid were **not evaluated**: {r['semantic']['reason']}."]

    L += ["", "### By query type", "", "| Type | n | " + " | ".join(
        f"{m.title()} nDCG@10" for m in modes) + " | " + " | ".join(f"{m.title()} MRR" for m in modes) + " |",
          "|---|---:|" + "---:|" * (2 * len(modes))]
    for t, s in r["retrieval"][modes[0]]["by_type"].items():
        L.append(f"| {t} | {s['n']} | " + " | ".join(f(r["retrieval"][m]["by_type"][t]["ndcg@10"]) for m in modes)
                 + " | " + " | ".join(f(r["retrieval"][m]["by_type"][t]["mrr"]) for m in modes) + " |")

    L += ["", "### Per query", "",
          "Top-3 shows document names from `queries.json`. RR = reciprocal rank of the first relevant document.", "",
          "| ID | Query | " + " | ".join(f"{m.title()} RR / top-3" for m in modes) + " |",
          "|---|---|" + "---|" * len(modes)]
    per = {m: {row["id"]: row for row in r["retrieval"][m]["per_query"]} for m in modes}
    for q in data["queries"]:
        cells = []
        for m in modes:
            row = per[m][q["id"]]
            cells.append(f"{f(row['rr@10'], 2)} · {', '.join(row['top3']) or '(none)'}")
        L.append(f"| {q['id']} | {q['query']} | " + " | ".join(cells) + " |")

    unjudged = r["retrieval"][modes[0]]["unjudged_queries"]
    L += ["", "### Queries with no relevant documents", "",
          "Recall, nDCG and RR are undefined here, so these are excluded from the means. "
          "Top similarity is the best chunk's cosine similarity (semantic mode); the RAG pipeline "
          f"refuses without calling the LLM below {0.25}.", "",
          "| ID | Query | Keyword hits | Semantic top similarity |", "|---|---|---:|---:|"]
    for qid in unjudged:
        kw = per["keyword"][qid]
        sem = per.get("semantic", {}).get(qid)
        L.append(f"| {qid} | {kw['query']} | {kw['returned']} | "
                 f"{f(sem['top_similarity']) if sem else 'unavailable'} |")

    rc = r["rag_checks"]
    L += ["", "## RAG reliability checks (automated, mocked model)", "",
          f"Real {rc['retrieval_mode']} retrieval (top {rc['top_k']}) feeds `rag.answer`; the LLM is replaced by "
          "fixed replies so the verification logic is tested deterministically. **These checks measure "
          "citation integrity and the rejection rules, not whether answers are factually correct.** "
          "A valid citation shows the quoted text exists in a retrieved source; it does not prove the "
          "answer follows from it.", "",
          "| Check | Passed |", "|---|---:|"]
    for name, (ok, n) in rc["checks"].items():
        L.append(f"| {CHECK_NAMES.get(name, name)} | {ok}/{n} |")
    missed = [row["id"] for row in rc["per_query"] if row.get("evidence_retrieved") is False]
    gated = [row["id"] for row in rc["per_query"] if row.get("gated_before_llm")]
    L += ["", f"- Answerable queries whose supporting chunk was **not** in the top {rc['top_k']}: "
              + (f"{', '.join(missed)} (no answer could be cited for these)." if missed else "none."),
          f"- Unanswerable queries refused by the similarity gate before any LLM call: {', '.join(gated) or 'none'}; "
          "the rest relied on the model's refusal and the number check."]

    g = r["groq"]
    L += ["", "## Real LLM answers (Groq)", ""]
    if g["status"] == "ran":
        L += [f"Model `{g['model']}`, {g['llm_calls']} calls, {g['prompt_tokens']} prompt + "
              f"{g['completion_tokens']} completion tokens. End-to-end p50 {f(g['p50_ms'], 0)} ms, "
              f"p95 {f(g['p95_ms'], 0)} ms. Estimated cost per LLM call: "
              + (f"${g['est_cost_per_llm_call_usd']:.6f} at {g['pricing_usd_per_m']} USD per million tokens."
                 if g["est_cost_per_llm_call_usd"] is not None else "not computed (no pricing supplied)."),
              "", "Answer correctness has **not** been judged automatically; see `MANUAL_REVIEW.md`."]
    else:
        L += [f"**Not run** ({g['reason']}). RAG end-to-end latency, token usage and cost are "
              "therefore unavailable; no values are estimated."]

    L += ["", "## Environment", "", "| | |", "|---|---|"]
    for k, v in env.items():
        L.append(f"| {k} | {v} |")
    L.append(f"| model load time (cold, from local cache) | "
             f"{f(r['semantic']['model_load_s'], 2) + ' s' if r['semantic']['available'] else 'unavailable'} |")
    for m, t in lat["modes"].items():
        L.append(f"| {m} latency samples | {t['samples']} ({t['distinct_queries']} distinct queries), "
                 f"mean {t['mean_ms']:.1f} ms, max {t['max_ms']:.1f} ms |")
    L += ["", "Latency notes: samples repeat the same queries, so they are not independent; p95 over "
          f"{lat['modes'][modes[0]]['samples']} samples is indicative only. {lat['measured']}.", ""]

    if analysis.exists():
        L += ["## Discussion", "", analysis.read_text(encoding="utf-8").strip(), ""]
    return "\n".join(L)
